# Tarjan SCC, iterative
index, low, onstk, stk, comp, cid = {}, {}, set(), [], {}, 0
counter = 0
for root in NODES:
    if root in index: continue
    work = [(root, iter(sorted(gedges[root])))]
    index[root] = low[root] = counter; counter += 1
    stk.append(root); onstk.add(root)
    while work:
        v, it = work[-1]
        adv = False
        for w in it:
            if w not in index:
                index[w] = low[w] = counter; counter += 1
                stk.append(w); onstk.add(w)
                work.append((w, iter(sorted(gedges[w]))))
                adv = True
                break
            elif w in onstk:
                low[v] = min(low[v], index[w])
        if adv: continue
        work.pop()
        if work:
            p = work[-1][0]
            low[p] = min(low[p], low[v])
        if low[v] == index[v]:
            while True:
                w = stk.pop(); onstk.discard(w); comp[w] = cid
                if w == v: break
            cid += 1

