# Runtime helpers identified by disassembly while building this graph:
BB_OBJECT_NEW      = 0x004A8F20   # bbObjectNew(BBClass*)      -> allocates, calls slot 0x10
BB_OBJECT_DOWNCAST = 0x004A8F60   # bbObjectDowncast(obj, BBClass*) -> obj or the null singleton
BB_ARRAY_NEW       = 0x004A63D0   # bbArrayNew(const char *type_tag, ndims, sizes) -> BBArray
NULL_OBJECT        = 0x005C9C80

# --- minimal PE reader, only needed to follow bbArrayNew's type-tag string ---
_PE = open(os.path.join(ROOT, "binary", "NSS5.exe"), "rb").read()
_e  = struct.unpack_from("<I", _PE, 0x3C)[0]
_IMG = struct.unpack_from("<I", _PE, _e + 24 + 28)[0]
_SECS = []
_so = _e + 24 + struct.unpack_from("<H", _PE, _e + 20)[0]
for _i in range(struct.unpack_from("<H", _PE, _e + 6)[0]):
    _o = _so + _i * 40
    _vs, _rva, _rs, _ro = struct.unpack_from("<IIII", _PE, _o + 8)
    _SECS.append((_IMG + _rva, _vs, _ro, _rs))

def rd32_at(va):
    for base, vs, ro, rs in _SECS:
        if base <= va < base + vs and va - base + 4 <= rs:
            return struct.unpack_from("<I", _PE, ro + (va - base))[0]
    return None

def cstr_at(va, lim=64):
    for base, vs, ro, rs in _SECS:
        if base <= va < base + vs and va - base < rs:
            o = ro + (va - base); x = o
            while x < len(_PE) and 32 <= _PE[x] < 127 and x - o < lim: x += 1
            return _PE[o:x].decode("ascii") if x < len(_PE) and _PE[x] == 0 else None
    return None

ARGS = {}   # call site VA -> (callee VA, [imm arg or None, ...])
for r in callargs:
    ARGS[ihex(r["site"])] = (ihex(r["callee"]),
                             [ihex(r["arg0"]), ihex(r["arg1"]), ihex(r["arg2"]), ihex(r["arg3"])])

def type_from_helper(site):
    """
    Static type of the value a runtime-helper call at `site` produces.
    For an ARRAY the element type is returned, matching the convention used for
    array-typed fields (a call through an array value is always on an element).
    """
    e = ARGS.get(site)
    if not e: return None
    callee, a = e
    if callee == BB_OBJECT_NEW      and a[0] is not None: return va2type.get(a[0])
    if callee == BB_OBJECT_DOWNCAST and a[1] is not None: return va2type.get(a[1])
    if callee == BB_ARRAY_NEW       and a[0] is not None:
        tag = cstr_at(a[0])
        return type_of_sig(tag) if tag else None
    return None

FN = {}
for r in fn_rows:
    a = ihex(r["addr"])
    FN[a] = dict(addr=a, name=r["name"], section=r["section"], size=int(r["size"]),
                 ninsn=int(r["ninsn"]))

def in_game(a):
    return a is not None and CODE_LO <= a < GAME_HI

def scope_of(a):
    if a is None: return "?"
    if in_game(a): return "game"
    if CODE_LO <= a < CODE_HI: return "module"      # BRL/PUB/3rd-party BlitzMax
    if TEXT_LO <= a <= TEXT_HI: return "runtime"    # BlitzMax C runtime
    return "extern"

# caller function -> its declaring type (if the caller is itself a known slot body)
def caller_type(a):
    ss = addr2slot.get(a)
    if not ss: return None, None, None
    t, k, n, g, s = ss[0]
    return t, k, g

# ============================================================================
# 3. Resolve indirect (virtual) call sites -- iterative fixpoint
# ============================================================================
# A receiver value is identified by a "value key":
#     ("param", caller_va, ebp_offset)   ("global", G)   ("ret", call_site)   ("imm", v)
# Seeds come from signatures and from the two runtime helpers whose class-table
# argument we recovered (bbObjectNew / bbObjectDowncast). Each site we resolve teaches
# us the return type of the call at that site, which seeds further sites, so we iterate
# to a fixpoint. Nothing is guessed: an unresolvable key stays unresolved and is
# reported in callgraph_unresolved.tsv.

STEP = re.compile(r"^([A-Z]{3})=\[([A-Z]{3})(\+idx)?\+(-?0x[0-9a-f]+)\]$")

def parse_chain(chain):
    """-> ordered field derefs [(disp, is_index)], BBClass load and terminal removed."""
    derefs, seen_vt = [], False
    for st in (c for c in chain.split(";") if c):
        m = STEP.match(st)
        if not m: continue
        src, idx, disp = m.group(2), m.group(3), int(m.group(4), 16)
        if src in ("EBP", "ESP"): continue
        if not seen_vt and disp == 0 and not idx:
            seen_vt = True; continue
        derefs.append((disp, bool(idx)))
    return derefs

class Site(object):
    __slots__ = ("caller", "site", "slot", "term", "chain", "derefs", "vkey", "cleanup")

sites = []
for r in indirect:
    if r["form"] == "abs" and r["vt"] == "0":
        continue                                   # IAT / import call
    s = Site()
    s.caller = ihex(r["caller"]); s.site = ihex(r["site"])
    s.term = r["term"]; s.chain = r["chain"]
    s.slot = int(r["slot"], 16) if (r["vt"] == "1" and r["slot"]) else None
    s.cleanup = int(r.get("cleanup", "-1") or -1)
    s.derefs = parse_chain(r["chain"]) if s.slot is not None else []
    t = s.term
    if   t.startswith("PARAM+"):  s.vkey = ("param", s.caller, int(t[6:], 16))
    elif t.startswith("GLOBAL:"): s.vkey = ("global", ihex(t[7:]))
    elif t.startswith("RETVAL:") and "@" in t: s.vkey = ("ret", ihex(t.split("@")[1]))
    elif t.startswith("IMM:"):    s.vkey = ("imm", ihex(t[4:]))
    else:                         s.vkey = None
    sites.append(s)

TYPEOF, EVID = {}, {}
DIRECT_AT = {ihex(r["site"]): ihex(r["callee"]) for r in direct if r["kind"] == "call"}

def sig_ret_type(callee):
    cands = {type_of_sig(parse_sig(g)[1]) for (_t, _k, _n, g, _s) in addr2slot.get(callee, [])}
    cands.discard(None)
    return cands.pop() if len(cands) == 1 else None

def learn(k, t, ev):
    if t and k not in TYPEOF:
        TYPEOF[k] = t; EVID[k] = ev; return 1
    return 0

# ---- seed A: parameters, from the caller's own recovered signature ----------
for s in sites:
    if not s.vkey or s.vkey[0] != "param" or s.vkey in TYPEOF: continue
    ct, ck, cg = caller_type(s.caller)
    if ct is None: continue
    frag = param_offsets(cg, ck == "Method").get(s.vkey[2])
    if frag is None: continue
    if frag == "SELF": learn(s.vkey, ct, "self")
    else:              learn(s.vkey, type_of_sig(frag), "param-sig")

# ---- seed B: call return values --------------------------------------------
for s in sites:
    if not s.vkey or s.vkey[0] != "ret" or s.vkey in TYPEOF: continue
    sv = s.vkey[1]
    if learn(s.vkey, type_from_helper(sv), "helper-classtable"): continue
    learn(s.vkey, sig_ret_type(DIRECT_AT.get(sv)), "callee-sig")

# ---- seed C: module-level Globals, from the stores that fill them -----------
# NOTE: extract_globals.py proves NSS5.exe carries NO BBDEBUGDECL_GLOBAL records, so a
# Global's declared type is not recoverable from metadata. The only evidence is (a) what
# gets stored into it and (b) what gets called through it.
GSTORE_SRC = defaultdict(list)      # global VA -> [inner call site VA]
for r in gstores:
    g = ihex(r["global"])
    if g is None: continue
    if r["term"].startswith("RETVAL:") and "@" in r["term"]:
        GSTORE_SRC[g].append(ihex(r["term"].split("@")[1]))

def seed_globals_from_stores():
    n = 0
    for g, srcs in GSTORE_SRC.items():
        if ("global", g) in TYPEOF: continue
        for sv in srcs:
            u = (type_from_helper(sv) or sig_ret_type(DIRECT_AT.get(sv))
                 or TYPEOF.get(("ret", sv)))
            if u:
                n += learn(("global", g), u, "store-from-" + H(sv))
                break
    return n

seed_globals_from_stores()

# ---- seed D: class-table immediates (static Function call on a Type) --------
for s in sites:
    if s.vkey and s.vkey[0] == "imm":
        learn(s.vkey, va2type.get(s.vkey[1]), "classtable-imm")

# ---- resolution machinery ---------------------------------------------------
# merged field table per type (own + inherited), offset -> (owner, name, sig)
FIELDS = {}
for t in ct_va:
    acc = {}
    for anc in reversed(ancestry(t)):
        for o, n, g in fields_of.get(anc, []):
            acc[o] = (anc, n, g)
    FIELDS[t] = acc

def field_at(t, off):
    return FIELDS.get(t, {}).get(off)

def apply_path(base, derefs):
    cur, trail = base, ""
    for disp, isidx in reversed(derefs):
        if isidx: continue          # BBArray element read; the array itself was the field
        f = field_at(cur, disp)
        if f is None: return None, "field+%#x-not-in-%s" % (disp, cur)
        owner, fname, fsig = f
        nxt = elem_type_of_sig(fsig) or type_of_sig(fsig)
        if nxt is None: return None, "field-%s.%s-not-object" % (owner, fname)
        cur = nxt; trail += "/%s.%s" % (owner, fname)
    return cur, trail

WHY = {"param": "param-untyped", "global": "global-untyped",
       "ret": "retval-untyped", "imm": "imm-not-classtable"}

def resolve_site(s):
    if s.slot is None: return None, "not-virtual-dispatch"
    if s.vkey is None: return None, "terminal:" + s.term.split(":")[0].split("@")[0]
    base = TYPEOF.get(s.vkey)
    if base is None: return None, WHY[s.vkey[0]]
    recv, trail = apply_path(base, s.derefs)
    if recv is None: return None, trail
    ent = FULL.get(recv, {}).get(s.slot)
    if ent is None: return None, "slot-not-in-%s" % recv
    owner, kind, name, sg, va = ent
    if va is None: return None, "slot-unresolved-in-%s" % recv
    return (recv, va, name, type_of_sig(parse_sig(sg)[1]),
            EVID.get(s.vkey, "?") + trail), None

def fixpoint():
    for _ in range(16):
        learned = 0
        for s in sites:
            k = ("ret", s.site)
            if k in TYPEOF: continue
            ok, _why = resolve_site(s)
            if ok and ok[3]: learned += learn(k, ok[3], "virtcall-ret")
        if not learned: return

fixpoint()

# ---- structural candidate sets ---------------------------------------------
# Sound constraint: for a value V, EVERY use site requires that the type T of V
#   (a) has a field at each byte offset the site dereferences, whose declared type
#       carries the next deref, and
#   (b) has the invoked slot in the merged slot table of the object the path lands on.
# A type failing any one site is impossible, so the TRUE type is always inside the
# candidate set. We therefore work in a candidate-set domain rather than insisting on
# a unique answer: a call site whose candidates all dispatch to one body is exactly
# resolved; one whose candidates dispatch to a handful of bodies still yields a sound
# OVER-approximation of the dependency edges, which is what a work-ordering graph needs
# (over-approximating can only make a function look less leaf-like than it is, never more).
key_sites = defaultdict(list)
for s in sites:
    if s.vkey and s.slot is not None:
        key_sites[s.vkey].append(s)

# cdecl stack cleanup after the call == 4 * (Self? + argument dwords). Verified against
# 2,235 already-exactly-resolved sites: 2,229 match to the byte (the 6 exceptions are
# Type Functions cleaning 4 bytes more than their signature accounts for), so this is a
# hard arity constraint on which slot bodies a call site can possibly be reaching.
def expected_cleanup(kind, sig):
    args, _ = parse_sig(sig)
    n = 1 if kind == "Method" else 0
    for a in args:
        n += 2 if a.strip() in ("l", "d") else 1
    return n * 4

def arity_ok(site, ent):
    if site.cleanup < 0: return True
    _o, kind, _n, sg, _v = ent
    exp = expected_cleanup(kind, sg)
    return site.cleanup == exp or (kind == "Function" and site.cleanup == exp + 4)

def compatible(t, ss):
    for s in ss:
        recv, _ = apply_path(t, s.derefs)
        if recv is None: return False
        ent = FULL.get(recv, {}).get(s.slot)
        if ent is None or not arity_ok(s, ent): return False
    return True

ALLT = sorted(ct_va)
CAND = {}
for k, ss in key_sites.items():
    if k in TYPEOF:
        CAND[k] = {TYPEOF[k]}
    else:
        CAND[k] = {t for t in ALLT if compatible(t, ss)}

# Second sound constraint on Globals: whatever is STORED into a Global must be
# assignable to it, so the Global's declared type is an ancestor of every stored
# value's static type. `mov [abs],reg` is the only way this codegen writes a Global,
# and NSS5CallGraph recorded all of them, so the union of ancestor sets is a valid
# upper bound. (Subtyping is why it is ancestors-of, not equal-to.)
def store_value_types(sv):
    """Possible static types of the value produced by the call at site `sv`."""
    u = type_from_helper(sv)
    if u: return {u}
    c = DIRECT_AT.get(sv)
    if c is not None:
        out = {type_of_sig(parse_sig(g)[1]) for (_t, _k, _n, g, _s) in addr2slot.get(c, [])}
        out.discard(None)
        if out: return out
    return set()

def value_types_at(sv):
    if ("ret", sv) in CAND: return CAND[("ret", sv)]
    return store_value_types(sv)

def apply_store_bounds():
    changed = 0
    for g, srcs in GSTORE_SRC.items():
        k = ("global", g)
        if k not in CAND or len(CAND[k]) == 1: continue
        b = set()
        for sv in srcs:
            for u in value_types_at(sv):
                b |= set(ancestry(u))
        if not b: continue
        n = CAND[k] & b
        if n and n != CAND[k]:
            CAND[k] = n; changed += 1
    return changed

