# ============================================================================
# 10. Re-render docs/specs/11 from the TSVs just written  (--render)
# ============================================================================
# Deliberately reads the TSVs back off disk rather than reusing the in-memory
# structures above: the document is then provably a view of the published data,
# not of intermediate state that never reached a file.

def render_doc(template, dst):
    dl = rd_tsv(os.path.join(EX, 'dep_layers.tsv'))
    lv = rd_tsv(os.path.join(EX, 'leaves.tsv'))
    wu = rd_tsv(os.path.join(EX, 'work_units.tsv'))
    tl = rd_tsv(os.path.join(EX, 'type_layers.tsv'))
    vs = rd_tsv(os.path.join(EX, 'vertical_slice.tsv'))
    gt = rd_tsv(os.path.join(EX, 'globals_typed.tsv'))
    out = {}

    # ---- leaves, full list grouped by type ---------------------------------
    clean = [r for r in lv if r['clean'] == '1']
    byt = defaultdict(list)
    for r in clean: byt[r['type']].append(r)
    L = []
    for t in sorted(byt, key=lambda x: (-len(byt[x]), x)):
        rows = sorted(byt[t], key=lambda r: -int(r['size']))
        L.append('\n**%s** - %d leaves, %d bytes\n' % (t, len(rows), sum(int(r['size']) for r in rows)))
        L.append('')
        L.append('| addr | function | bytes | callers | unit |')
        L.append('|---|---|---:|---:|---|')
        for r in rows:
            L.append('| `%s` | `%s` | %s | %s | %s |' % (r['addr'], r['label'], r['size'], r['n_callers'], r['unit']))
    out['leaves_full'] = '\n'.join(L)

    b = Counter()
    for r in clean:
        n = int(r['size'])
        b['≥1024' if n >= 1024 else '512-1023' if n >= 512 else '256-511' if n >= 256
          else '128-255' if n >= 128 else '64-127' if n >= 64 else '<64'] += 1
    order = ['<64', '64-127', '128-255', '256-511', '512-1023', '≥1024']
    out['leaf_buckets'] = '\n'.join(
        ['| size band | count |', '|---|---:|'] + ['| %s | %d |' % (k, b[k]) for k in order])

    out['leaf_top'] = '\n'.join(
        ['| addr | function | bytes | callers |', '|---|---|---:|---:|'] +
        ['| `%s` | `%s` | %s | %s |' % (r['addr'], r['label'], r['size'], r['n_callers'])
         for r in sorted(clean, key=lambda r: -int(r['size']))[:40]])

    # ---- type layers -------------------------------------------------------
    byl = defaultdict(list)
    for r in tl: byl[int(r['layer'])].append(r)
    L = ['| layer | types | slots | bytes | members |', '|---:|---:|---:|---:|---|']
    for k in sorted(byl):
        rs = byl[k]
        L.append('| %d | %d | %d | %d | %s |' % (
            k, len(rs), sum(int(x['n_slots']) for x in rs), sum(int(x['bytes']) for x in rs),
            ' '.join('`%s`' % x['type'] for x in sorted(rs, key=lambda y: y['type']))))
    out['type_layers'] = '\n'.join(L)

    out['type_hubs'] = '\n'.join(
        ['| type | layer | slots | bytes | depends on | depended on by |', '|---|---:|---:|---:|---:|---:|'] +
        ['| `%s` | %s | %s | %s | %s | %s |' % (r['type'], r['layer'], r['n_slots'], r['bytes'],
                                                r['n_deps'], r['n_dependents'])
         for r in sorted(tl, key=lambda r: -int(r['n_dependents']))[:20]])

    # ---- function layers ---------------------------------------------------
    h = Counter(int(r['layer_certain']) for r in dl)
    hb = Counter(int(r['layer']) for r in dl)
    bb = defaultdict(int)
    for r in dl: bb[int(r['layer_certain'])] += int(r['size'])
    out['fn_layers'] = '\n'.join(
        ['| layer | functions (certain) | bytes (certain) | functions (sound) |', '|---:|---:|---:|---:|'] +
        ['| %d | %d | %d | %d |' % (k, h[k], bb[k], hb.get(k, 0)) for k in sorted(set(h) | set(hb))])

    # ---- work units --------------------------------------------------------
    def unit_table(rows):
        return '\n'.join(
            ['| unit | contents | layer | fns | bytes | effort | unresolved | in slice | deps |',
             '|---|---|---:|---:|---:|:---:|---:|---:|---|'] +
            ['| **%s** | `%s` | %s | %s | %s | %s | %s | %s | %s |' %
             (r['unit'], r['name'], r['layer'], r['n_fns'], r['bytes'], r['effort'],
              r['n_unresolved'], r['n_in_slice'],
              (r['deps'][:60] + '…') if len(r['deps']) > 60 else (r['deps'] or '-'))
             for r in rows])
    out['units_ready'] = unit_table([r for r in wu if r['ready'] == '1'])
    out['units_l0_l3'] = unit_table([r for r in wu if int(r['layer']) <= 3])
    out['units_all'] = unit_table(wu)
    out['unit_effort'] = '\n'.join(
        ['| effort | bytes | units | functions |', '|---|---|---:|---:|'] +
        ['| %s | %s | %d | %d |' % (e, rng,
                                    sum(1 for r in wu if r['effort'] == e),
                                    sum(int(r['n_fns']) for r in wu if r['effort'] == e))
         for e, rng in (('S', '< 2 000'), ('M', '2 000 - 5 999'), ('L', '6 000 - 14 999'), ('XL', '≥ 15 000'))])

    # ---- vertical slice ----------------------------------------------------
    cs = [r for r in vs if r['certain'] == '1']
    c = Counter(); bt = Counter()
    for r in cs: c[r['type']] += 1; bt[r['type']] += int(r['size'])
    out['slice_by_type'] = '\n'.join(
        ['| type | functions | bytes |', '|---|---:|---:|'] +
        ['| `%s` | %d | %d |' % (t, n, bt[t]) for t, n in c.most_common()])

    grp = defaultdict(lambda: [0, 0])
    for r in cs:
        for g in r['groups'].split(','):
            if g: grp[g][0] += 1; grp[g][1] += int(r['size'])

    matchonly = [r for r in cs if 'match' in r['groups']]
    out['slice_match'] = '\n'.join(
        ['| addr | function | type | bytes | layer |', '|---|---|---|---:|---:|'] +
        ['| `%s` | `%s` | %s | %s | %s |' % (r['addr'], r['label'], r['type'], r['size'], r['layer_certain'])
         for r in sorted(matchonly, key=lambda r: -int(r['size']))[:60]])

    # ---- globals -----------------------------------------------------------
    out['globals_top'] = '\n'.join(
        ['| global | inferred type | call sites | evidence |', '|---|---|---:|---|'] +
        ['| `%s` | `%s` | %s | %s |' % (r['global'], r['type'], r['nsites'], r['evidence'])
         for r in sorted([x for x in gt if x['type']], key=lambda x: -int(x['nsites']))[:25]])

    # ---- cycles ------------------------------------------------------------
    cyc = [r for r in dl if r['scc_size_certain'] != '1']
    out['cycles'] = '\n'.join(
        ['| addr | function | bytes | layer |', '|---|---|---:|---:|'] +
        ['| `%s` | `%s` | %s | %s |' % (r['addr'], r['label'], r['size'], r['layer_certain'])
         for r in sorted(cyc, key=lambda r: r['scc'])])

    bigscc = Counter(r['type'] for r in dl if r['scc_size'] == '242')
    out['bigscc'] = '\n'.join(
        ['| type | functions in the SCC |', '|---|---:|'] +
        ['| `%s` | %d |' % (t, n) for t, n in bigscc.most_common()])

    src = io.open(template, encoding='utf-8').read()
    for k, v in out.items():
        src = src.replace('<<<%s>>>' % k, v)
    io.open(dst, 'w', encoding='utf-8', newline='\n').write(src)
    print('wrote', dst, len(src), 'chars')
    for k in out:
        if '<<<%s>>>' % k in src: print('UNSUBSTITUTED', k)


if RENDER:
    render_doc(POSARGS[0] if POSARGS else TEMPLATE,
               POSARGS[1] if len(POSARGS) > 1 else TARGET)
