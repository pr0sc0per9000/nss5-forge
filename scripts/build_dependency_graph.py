#!/usr/bin/env python3
"""
build_dependency_graph.py -- turn the raw Ghidra call-graph observation into the
reconstruction dependency graph.

    python scripts/build_dependency_graph.py             # rebuild the TSVs
    python scripts/build_dependency_graph.py --render    # ... and re-render the document
    python scripts/build_dependency_graph.py --render <template> <target>

INPUTS
  extracted/vtable_map.tsv                   slot -> code address (generated by resolve_vtables.py)
  extracted/class_tables.tsv                 class table VA, super, instance size
  extracted/object_model.json                fields (offset + type sig) and method signatures
  extracted/ghidra/function_inventory.tsv    every function, size, caller counts
  extracted/callgraph/callgraph_functions.tsv
  extracted/callgraph/callgraph_direct.tsv
  extracted/callgraph/callgraph_indirect.tsv
  extracted/callgraph/callgraph_globalstores.tsv

OUTPUTS (all into extracted/)
  callgraph_resolved.tsv     one row per call edge, with the resolution and its evidence
  callgraph_unresolved.tsv   the indirect sites we could NOT resolve, with why
  globals_typed.tsv          module-level Global VA -> inferred type + evidence
  dep_layers.tsv             per function: scc, layer, in-scope fan-in/fan-out
  type_deps.tsv              Type -> Type edges from field types and method signatures
  type_layers.tsv            per Type: scc, layer
  leaves.tsv                 functions with no in-scope callees
  vertical_slice.tsv         functions reachable from the boot/menu/match roots
  work_units.tsv             proposed pass-sized batches

DOCUMENT (--render only)
  The reconstruction dependency-graph document (TARGET below, overridable on the
  command line) is rewritten from the TSVs above, so the published document cannot
  drift from the data. Every table in it is generated; only the prose is hand-written,
  in scripts/templates/11-reconstruction-dependency-graph.template.md with <<<name>>>
  markers. Rendering is the second half of one pipeline, which is why it lives here
  rather than in a separate script.

RESOLUTION MODEL (indirect calls)
  Legacy BlitzMax method dispatch is  `mov R,[Self] ; call dword ptr [R + slot]`.
  NSS5CallGraph.java recorded, per site, the slot and a backward def-use chain ending in a
  terminal (PARAM+0x8 = Self, PARAM+0xN, GLOBAL:VA, RETVAL:VA, IMM:VA, LOCAL...).
  Here we turn the terminal + the intervening field/array derefs into a static receiver
  TYPE, then look the slot up in that type's merged (own + inherited) slot table.
  Everything that cannot be typed is reported, not guessed.
"""

