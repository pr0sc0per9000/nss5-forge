def reach(seeds, gr=None):
    gr = gr if gr is not None else gedges
    seen, dq = set(), deque(x for x in seeds if x in NSET)
    seen |= set(dq)
    while dq:
        x = dq.popleft()
        for y in gr[x]:
            if y not in seen: seen.add(y); dq.append(y)
    return seen

