def site_targets(s):
    """Sound set of possible callee addresses for one virtual call site."""
    cs = CAND.get(s.vkey)
    if not cs: return None
    out = set()
    for t in cs:
        recv, _ = apply_path(t, s.derefs)
        if recv is None: continue
        ent = FULL.get(recv, {}).get(s.slot)
        if ent is None or not arity_ok(s, ent): continue
        if ent[4]: out.add(ent[4])
        # a virtual call may land on an override in any subtype of the static type
        for sub in subtypes.get(recv, ()):
            e2 = FULL.get(sub, {}).get(s.slot)
            if e2 and e2[4]: out.add(e2[4])
    out.discard(ABSTRACT_STUB)
    return out

def ret_types(targets):
    out = set()
    for va in targets:
        for (_t, _k, _n, g, _s) in addr2slot.get(va, []):
            u = type_of_sig(parse_sig(g)[1])
            if u: out.add(u)
    return out

