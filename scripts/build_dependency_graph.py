model = json.load(io.open(os.path.join(EX, "object_model.json"), encoding="utf-8-sig"))
vmap  = rd_tsv(os.path.join(EX, "vtable_map.tsv"))
ctab  = rd_tsv(os.path.join(EX, "class_tables.tsv"))

ct_va      = {r["type"]: int(r["classtable_va"], 16) for r in ctab}
super_of   = {r["type"]: (r["super_type"] if r["super_type"] != "Object(runtime)" else None) for r in ctab}
inst_size  = {r["type"]: int(r["instance_size"]) for r in ctab}
va2type    = {v: t for t, v in ct_va.items()}
GAME_TYPES = {t for t, v in ct_va.items() if v < GAME_CT_HI}
REAL_GAME_TYPES = {t for t in GAME_TYPES if not t.startswith("z_")}

fields_of  = defaultdict(list)   # type -> [(offset, name, sig)]
own_slots  = defaultdict(dict)   # type -> {slot: (kind,name,sig)}
for e in model:
    for m in e["members"]:
        if m["kind"] == "Field":
            fields_of[e["type"]].append((m["offset"], m["name"], m["sig"]))
        else:
            own_slots[e["type"]][m["offset"]] = (m["kind"], m["name"], m["sig"])

slot_va = defaultdict(dict)      # type -> {slot: va}
slot_status = defaultdict(dict)
for r in vmap:
    va = ihex(r["va"])
    slot_va[r["type"]][int(r["slot"], 16)] = va
    slot_status[r["type"]][int(r["slot"], 16)] = r["status"]

def ancestry(t):
    out, seen = [], set()
    while t and t not in seen:
        seen.add(t); out.append(t); t = super_of.get(t)
    return out

# merged (own + inherited) slot table per type
FULL = {}      # type -> {slot: (owner_type, kind, name, sig, va)}
for t in ct_va:
    acc = {}
    for anc in reversed(ancestry(t)):            # base first, derived overrides
        for s, (k, n, g) in own_slots.get(anc, {}).items():
            acc[s] = (anc, k, n, g, slot_va[anc].get(s))
    # a derived type re-points inherited slots in its own class table, so prefer its VA
    for s in list(acc):
        if s in slot_va.get(t, {}):
            o, k, n, g, _ = acc[s]
            acc[s] = (o, k, n, g, slot_va[t][s])
    FULL[t] = acc

subtypes = defaultdict(set)
for t in ct_va:
    for anc in ancestry(t)[1:]:
        subtypes[anc].add(t)

# address -> the slot(s) that point at it
addr2slot = defaultdict(list)
for r in vmap:
    va = ihex(r["va"])
    if va and r["status"] == "OK":
        addr2slot[va].append((r["type"], r["kind"], r["name"], r["sig"], int(r["slot"], 16)))

def label_of(va):
    ss = addr2slot.get(va)
    if ss:
        t, k, n, g, s = ss[0]
        extra = ("+%d" % (len(ss) - 1)) if len(ss) > 1 else ""
        return "%s.%s%s" % (t, n, extra)
    return None

# ---- signature parsing -----------------------------------------------------
def split_args(argstr):
    out, depth, cur = [], 0, ""
    for ch in argstr:
        if ch == "(" or ch == "[": depth += 1
        elif ch == ")" or ch == "]": depth -= 1
        if ch == "," and depth == 0:
            out.append(cur); cur = ""
        else:
            cur += ch
    if cur.strip(): out.append(cur)
    return [a for a in out if a != ""]

def parse_sig(sig):
    """'(:TFixture,:TTeam,:TTeam,()i)i' -> (['(:TFixture','..'], 'i')"""
    if not sig or not sig.startswith("("): return [], sig or ""
    depth = 0
    for i, ch in enumerate(sig):
        if ch == "(": depth += 1
        elif ch == ")":
            depth -= 1
            if depth == 0:
                return split_args(sig[1:i]), sig[i + 1:]
    return [], ""

def type_of_sig(s):
    """Object type named by a signature fragment, else None."""
    s = (s or "").strip()
    while s.startswith("[]") or s.startswith("*"):
        s = s[2:] if s.startswith("[]") else s[1:]
    if s.startswith(":"): return s[1:]
    return None

def elem_type_of_sig(s):
    s = (s or "").strip()
    if s.startswith("[]"): return type_of_sig(s[2:])
    return None

ARGSZ = {"l": 8, "d": 8}
def param_offsets(sig, is_method):
    """stack offset -> signature fragment, cdecl, Self at +8 for Methods."""
    args, _ = parse_sig(sig)
    off, out = 8, {}
    if is_method:
        out[8] = "SELF"; off = 12
    for a in args:
        out[off] = a
        off += ARGSZ.get(a.strip(), 4)
    return out

