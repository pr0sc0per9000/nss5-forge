direct   = rd_tsv(os.path.join(CG, "callgraph_direct.tsv"))
indirect = rd_tsv(os.path.join(CG, "callgraph_indirect.tsv"))
gstores  = rd_tsv(os.path.join(CG, "callgraph_globalstores.tsv"))
