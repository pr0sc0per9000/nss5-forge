def rd_tsv(path):
    with io.open(path, encoding="utf-8-sig", newline="") as fh:
        return list(csv.DictReader(fh, delimiter="\t"))

def H(v):  return "0x%08x" % v
def ihex(s):
    s = (s or "").strip()
    if not s: return None
    try: return int(s, 16)
    except ValueError: return None

