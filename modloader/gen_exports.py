"""Write exports.S and winmm.def from the real 32-bit winmm.dll.

The proxy has to export everything the real winmm.dll exports, not just the 16 functions
NSS5.exe imports. Once our winmm.dll is loaded, every other module in the process that
imports winmm (OpenAL, the sound and graphics drivers) binds to ours as well.

Each export becomes a stub that jumps through g_real[i]; winmm.c fills g_real at load.
Ordinals are kept. Ordinal-only exports stay ordinal-only.

Usage: python modloader/gen_exports.py [path to 32-bit winmm.dll]
"""

import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT = os.path.join(os.environ.get("SystemRoot", r"C:\Windows"), "SysWOW64", "winmm.dll")


def exports(path):
    b = open(path, "rb").read()
    pe = struct.unpack_from("<I", b, 0x3C)[0]
    nsec = struct.unpack_from("<H", b, pe + 6)[0]
    optsz = struct.unpack_from("<H", b, pe + 20)[0]
    opt = pe + 24
    if struct.unpack_from("<H", b, opt)[0] != 0x10B:
        sys.exit("not a 32-bit PE: %s" % path)
    secs = []
    for i in range(nsec):
        s = pe + 24 + optsz + i * 40
        vs, va, rs, raw = struct.unpack_from("<IIII", b, s + 8)
        secs.append((va, max(vs, rs), raw))

    def off(rva):
        for va, sz, raw in secs:
            if va <= rva < va + sz:
                return rva - va + raw
        raise ValueError(hex(rva))

    def cstr(rva):
        o = off(rva)
        return b[o:b.index(b"\0", o)].decode()

    erva = struct.unpack_from("<I", b, opt + 96)[0]
    e = off(erva)
    base, nfunc, nname, afunc, aname, aord = struct.unpack_from("<IIIIII", b, e + 16)
    names = {}
    for i in range(nname):
        n = cstr(struct.unpack_from("<I", b, off(aname) + 4 * i)[0])
        names[struct.unpack_from("<H", b, off(aord) + 2 * i)[0]] = n
    out = []
    for i in range(nfunc):
        if struct.unpack_from("<I", b, off(afunc) + 4 * i)[0]:
            out.append((base + i, names.get(i)))
    return out


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else DEFAULT
    ex = exports(src)
    with open(os.path.join(HERE, "winmm.def"), "w", newline="\n") as f:
        f.write("; generated by gen_exports.py from %s\n" % os.path.basename(src))
        f.write("LIBRARY winmm.dll\nEXPORTS\n")
        for i, (ordinal, name) in enumerate(ex):
            if name:
                f.write("  %s=stub_%d @%d\n" % (name, i, ordinal))
            else:
                f.write("  ord_%d=stub_%d @%d NONAME\n" % (ordinal, i, ordinal))
    with open(os.path.join(HERE, "exports.S"), "w", newline="\n") as f:
        f.write("/* generated by gen_exports.py: one jump stub per winmm export */\n")
        f.write("\t.text\n")
        for i, _ in enumerate(ex):
            f.write("\t.globl _stub_%d\n_stub_%d:\tjmp *_g_real+%d\n" % (i, i, 4 * i))
    with open(os.path.join(HERE, "exports.h"), "w", newline="\n") as f:
        f.write("/* generated by gen_exports.py: name or ordinal of each g_real slot */\n")
        f.write("#define EXPORT_COUNT %d\n" % len(ex))
        f.write("static const struct { const char *name; unsigned short ordinal; } "
                "g_exports[EXPORT_COUNT] = {\n")
        for ordinal, name in ex:
            f.write('\t{ %s, %d },\n' % ('"%s"' % name if name else "0", ordinal))
        f.write("};\n")
    print("%d exports (%d ordinal-only) from %s" % (len(ex), sum(1 for _, n in ex if not n), src))


if __name__ == "__main__":
    main()
